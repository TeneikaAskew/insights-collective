#!/usr/bin/env node
// ABOUTME: Prints seed.sql from fixtures.mjs. `node gen-seed.mjs > seed.sql`; the self-test fails if the checked-in file differs.
import { COURSES, MODULES, ID_PREFIX } from './fixtures.mjs';

const lit = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `E'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\t/g, '\\t')}'`);
const out = [];
out.push('-- ABOUTME: GENERATED by gen-seed.mjs from fixtures.mjs; do not edit. Synthetic anonymous public-catalog fixture.');
out.push('-- ABOUTME: INSERT-only, one transaction, refuses a non-pristine stack. No UPDATE/DELETE/DDL/grant/policy.');
out.push('\\set ON_ERROR_STOP on');
out.push('begin;');
out.push('do $pristine$ begin');
out.push("  if (select count(*) from public.courses) <> 0 or (select count(*) from public.modules) <> 0 then");
out.push("    raise exception 'PUBLIC_CATALOG_E_NOT_PRISTINE: courses/modules already hold rows; this lane seeds only a fresh owned stack';");
out.push('  end if;');
out.push('end $pristine$;');
for (const c of COURSES) {
  out.push(`insert into public.courses (id, title, description, category, level, estimated_hours, duration, published, status, created_at, updated_at, instructor_id) values (${lit(c.id)}::uuid, ${lit(c.title)}, ${lit('Synthetic public-catalog fixture.')}, ${lit(c.category)}, ${lit(c.level)}, ${lit(c.estimated_hours)}, ${lit(c.duration)}, ${lit(c.published)}, ${lit(c.status)}, ${lit(c.created_at)}::timestamptz, ${lit(c.created_at)}::timestamptz, null);`);
}
for (const m of MODULES) {
  out.push(`insert into public.modules (id, course_id, title, week, "position", published) values (${lit(m.id)}::uuid, ${lit(m.course_id)}::uuid, ${lit(m.title)}, ${m.week}, ${m.position}, ${lit(m.published)});`);
}
out.push(`do $count$ begin`);
out.push(`  if (select count(*) from public.courses where id::text like '${ID_PREFIX}%') <> ${COURSES.length} or (select count(*) from public.courses) <> ${COURSES.length} then raise exception 'PUBLIC_CATALOG_E_SEED_COUNT courses'; end if;`);
out.push(`  if (select count(*) from public.modules where id::text like '${ID_PREFIX}%') <> ${MODULES.length} or (select count(*) from public.modules) <> ${MODULES.length} then raise exception 'PUBLIC_CATALOG_E_SEED_COUNT modules'; end if;`);
out.push(`end $count$;`);
out.push('commit;');
process.stdout.write(out.join('\n') + '\n');
